#!/usr/bin/env swift
// Generates Sources/MdvCore/Generated/HTMLEntityTable.swift from the WHATWG named character
// reference table (https://html.spec.whatwg.org/entities.json).
//
// Usage: swift scripts/generate-html-entities.swift ENTITIES_JSON OUTPUT
//
// Run through `make html-entities`, which downloads entities.json. The HTML standard says the
// list is static and will not change. Output is sorted by name and uses only ASCII (values are
// written as `\u{...}` escapes), so regenerating produces the same file byte for byte.

import Foundation

struct Entry: Decodable {
    let codepoints: [UInt32]
}

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("generate-html-entities: \(message)\n".utf8))
    exit(1)
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    fail("usage: generate-html-entities.swift ENTITIES_JSON OUTPUT")
}
let (inputPath, outputPath) = (arguments[1], arguments[2])

let entries: [String: Entry]
do {
    entries = try JSONDecoder().decode([String: Entry].self, from: Data(contentsOf: URL(fileURLWithPath: inputPath)))
} catch {
    fail("cannot read \(inputPath): \(error)")
}

/// Name (without `&` and `;`) to value.
var terminated: [String: String] = [:]
/// Legacy names browsers also decode without a `;`.
var legacy: [String: String] = [:]
for (key, entry) in entries {
    guard key.hasPrefix("&") else {
        fail("unexpected key \(key.debugDescription)")
    }
    let hasSemicolon = key.hasSuffix(";")
    let name = String(key.dropFirst().dropLast(hasSemicolon ? 1 : 0))
    guard name.range(of: "^[A-Za-z0-9]+$", options: .regularExpression) != nil else {
        fail("unexpected name \(key.debugDescription)")
    }
    let scalars = entry.codepoints.compactMap(Unicode.Scalar.init)
    guard !scalars.isEmpty, scalars.count == entry.codepoints.count else {
        fail("invalid code points for \(key)")
    }
    let value = scalars.map { "\\u{\(String($0.value, radix: 16, uppercase: true))}" }.joined()
    if hasSemicolon {
        terminated[name] = value
    } else {
        legacy[name] = value
    }
}
guard terminated.count > 2000, !legacy.isEmpty else {
    fail("too few entries in \(inputPath)")
}
for name in legacy.keys where terminated[name] == nil {
    fail("legacy name \(name) has no ;-terminated form")
}

func table(_ table: [String: String]) -> String {
    table.sorted { $0.key < $1.key }.map { "        \"\($0.key)\": \"\($0.value)\",\n" }.joined()
}

let output = """
    // Generated by scripts/generate-html-entities.swift (`make html-entities`). Do not edit.
    //
    // Source: https://html.spec.whatwg.org/entities.json (the HTML Standard's named character
    // references; the standard says the list is static).

    // swiftlint:disable file_length

    extension HTMLEntities {
        /// Every named character reference: name (without `&` and `;`) to value.
        static let all: [String: String] = [
    \(table(terminated))    ]

        /// The legacy names browsers also decode without a `;`, to their value.
        static let legacy: [String: String] = [
    \(table(legacy))    ]
    }

    """

do {
    try Data(output.utf8).write(to: URL(fileURLWithPath: outputPath), options: .atomic)
} catch {
    fail("cannot write \(outputPath): \(error)")
}
