#!/usr/bin/env swift
// Generates Sources/MdvCore/Generated/EmojiTable.swift from github/gemoji's db/emoji.json.
//
// Usage: swift scripts/generate-emoji.swift EMOJI_JSON SOURCE_COMMIT OUTPUT
//
// Run through `make emoji`, which downloads emoji.json at the pinned commit. Output is sorted
// by alias and uses only ASCII (characters are written as `\u{...}` escapes), so regenerating
// from the same input produces the same file byte for byte.

import Foundation

struct Entry: Decodable {
    /// Absent for GitHub's custom image emoji, which have no Unicode character.
    let emoji: String?
    let aliases: [String]
}

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("generate-emoji: \(message)\n".utf8))
    exit(1)
}

let arguments = CommandLine.arguments
guard arguments.count == 4 else {
    fail("usage: generate-emoji.swift EMOJI_JSON SOURCE_COMMIT OUTPUT")
}
let (inputPath, commit, outputPath) = (arguments[1], arguments[2], arguments[3])
guard commit.range(of: "^[0-9a-f]{40}$", options: .regularExpression) != nil else {
    fail("SOURCE_COMMIT must be a full 40-character commit SHA")
}

let entries: [Entry]
do {
    entries = try JSONDecoder().decode([Entry].self, from: Data(contentsOf: URL(fileURLWithPath: inputPath)))
} catch {
    fail("cannot read \(inputPath): \(error)")
}

var table: [String: String] = [:]
for entry in entries {
    guard let emoji = entry.emoji, !emoji.isEmpty else {
        continue
    }
    for alias in entry.aliases {
        guard alias.range(of: "^[a-z0-9_+-]+$", options: .regularExpression) != nil else {
            fail("unexpected alias \(alias.debugDescription)")
        }
        if let existing = table[alias], existing != emoji {
            fail("alias \(alias) maps to two emoji")
        }
        table[alias] = emoji
    }
}
guard !table.isEmpty else {
    fail("no emoji found in \(inputPath)")
}

func escaped(_ emoji: String) -> String {
    emoji.unicodeScalars.map { "\\u{\(String($0.value, radix: 16, uppercase: true))}" }.joined()
}

var output = """
    // Generated by scripts/generate-emoji.swift (`make emoji`). Do not edit.
    //
    // Source: https://github.com/github/gemoji/blob/\(commit)/db/emoji.json
    // gemoji is Copyright (c) 2019 GitHub, Inc., MIT License:
    // https://github.com/github/gemoji/blob/\(commit)/LICENSE

    // swiftlint:disable file_length

    extension EmojiShortcodes {
        /// GitHub emoji shortcode aliases (without colons) mapped to their emoji. Custom image
        /// emoji such as `octocat` have no Unicode character and are not included.
        static let table: [String: String] = [

    """
for (alias, emoji) in table.sorted(by: { $0.key < $1.key }) {
    output += "        \"\(alias)\": \"\(escaped(emoji))\",\n"
}
output += "    ]\n}\n"

do {
    try Data(output.utf8).write(to: URL(fileURLWithPath: outputPath), options: .atomic)
} catch {
    fail("cannot write \(outputPath): \(error)")
}
