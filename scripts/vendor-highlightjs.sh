#!/usr/bin/env bash
# Vendors a pinned highlight.js build into MdvCore as generated Swift source.
#
#   scripts/vendor-highlightjs.sh 11.12.0     (or: make vendor-highlightjs HLJS_VERSION=11.12.0)
#
# Fetches the common bundle plus EXTRA_LANGUAGES from highlightjs/cdn-release at the given tag,
# records each file's URL and SHA-256 in Vendor/highlight.js/MANIFEST, copies the BSD-3
# license, and writes Sources/MdvCore/Highlighting/HighlightJSSource.generated.swift.
set -euo pipefail

VERSION="${1:-}"
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "usage: $0 VERSION (e.g. 11.12.0)" >&2
  exit 64
fi

# Languages not in the common bundle, loaded after it (build/languages/NAME.min.js).
EXTRA_LANGUAGES=(cmake dart dockerfile elixir haskell nginx powershell scala)

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BASE_URL="https://raw.githubusercontent.com/highlightjs/cdn-release/$VERSION"
VENDOR_DIR="$ROOT/Vendor/highlight.js"
OUTPUT="$ROOT/Sources/MdvCore/Highlighting/HighlightJSSource.generated.swift"

WORK="$(mktemp -d)"
trap 'command rm -rf "$WORK"' EXIT

fetch() {
  curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 -o "$2" "$1"
}

files=(build/highlight.min.js)
for language in "${EXTRA_LANGUAGES[@]}"; do
  files+=("build/languages/$language.min.js")
done

manifest="$WORK/MANIFEST"
{
  echo "# highlight.js vendored by scripts/vendor-highlightjs.sh. Do not edit."
  echo "version $VERSION"
  echo "license BSD-3-Clause ($BASE_URL/LICENSE)"
  echo "# sha256 url"
} >"$manifest"

fetch "$BASE_URL/LICENSE" "$WORK/LICENSE"

# Picks a raw-string delimiter (#…#) that the JavaScript can't terminate or interpolate with.
delimiter_for() {
  local hashes="#"
  while grep -qF -- "\"$hashes" "$1" || grep -qF -- "\\$hashes" "$1"; do
    hashes="$hashes#"
  done
  printf '%s' "$hashes"
}

swift="$WORK/source.swift"
{
  echo "// swift-format-ignore-file"
  echo "// Generated by scripts/vendor-highlightjs.sh from highlight.js $VERSION. Do not edit."
  echo "// highlight.js: Copyright (c) 2006, Ivan Sagalaev and other contributors. BSD-3-Clause;"
  echo "// see Vendor/highlight.js/LICENSE. URLs and SHA-256 sums: Vendor/highlight.js/MANIFEST."
  echo
  echo "/// The vendored highlight.js scripts, evaluated in order by \`HighlightJSHighlighter\`."
  echo "enum HighlightJSSource {"
  echo "    static let version = \"$VERSION\""
  echo
  echo "    /// The common bundle (defines \`hljs\`), then extra languages that register with it."
  echo "    static let scripts: [(name: String, source: String)] = ["
} >"$swift"

for file in "${files[@]}"; do
  name="$(basename "$file")"
  fetch "$BASE_URL/$file" "$WORK/$name"
  if LC_ALL=C grep -q $'\r' "$WORK/$name"; then
    echo "error: $name contains carriage returns" >&2
    exit 1
  fi
  sum="$(shasum -a 256 "$WORK/$name" | cut -d' ' -f1)"
  echo "$sum $BASE_URL/$file" >>"$manifest"
  hashes="$(delimiter_for "$WORK/$name")"
  {
    echo "        ("
    echo "            \"$name\","
    echo "            $hashes\"\"\""
    cat "$WORK/$name"
    # Ensure the closing delimiter starts its own line.
    [[ "$(tail -c 1 "$WORK/$name")" == "" ]] || echo
    echo "\"\"\"$hashes"
    echo "        ),"
  } >>"$swift"
done

{
  echo "    ]"
  echo "}"
} >>"$swift"

mkdir -p "$VENDOR_DIR"
command cp -f "$WORK/LICENSE" "$VENDOR_DIR/LICENSE"
command cp -f "$manifest" "$VENDOR_DIR/MANIFEST"
command cp -f "$swift" "$OUTPUT"
echo "Vendored highlight.js $VERSION:"
cat "$VENDOR_DIR/MANIFEST"
