#!/usr/bin/env bash
# Vendors a pinned sindresorhus/github-markdown-css release into PeepCore as generated Swift.
#
#   scripts/vendor-github-markdown-css.sh 5.9.0   (or: make vendor-github-markdown-css GHCSS_VERSION=5.9.0)
#
# Fetches github-markdown.css (light and dark, by prefers-color-scheme) at the release tag,
# records its URL and SHA-256 in Vendor/github-markdown-css/MANIFEST, copies the MIT license,
# and writes Sources/PeepCore/Themes/GitHubMarkdownCSS.generated.swift.
#
# The CSS is adjusted to Peep's theme rules (docs/VISION.md, "Themes"); each edit must match
# exactly as often as expected, or the script fails so a new release gets a human look:
# - dark colors apply on screen only (`@media screen and (prefers-color-scheme: dark)`), and the
#   light colors on paper too (`@media not screen and (prefers-color-scheme: dark)`), so print is
#   always light;
# - the heading anchors' `mask-image: url("data:…")` octicon is dropped: theme CSS loads
#   nothing through `url()` (Peep's anchors are a text glyph, see GitHubTheme.swift).
set -euo pipefail

VERSION="${1:-}"
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "usage: $0 VERSION (e.g. 5.9.0)" >&2
  exit 64
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BASE_URL="https://raw.githubusercontent.com/sindresorhus/github-markdown-css/v$VERSION"
VENDOR_DIR="$ROOT/Vendor/github-markdown-css"
OUTPUT="$ROOT/Sources/PeepCore/Themes/GitHubMarkdownCSS.generated.swift"

WORK="$(mktemp -d)"
trap 'command rm -rf "$WORK"' EXIT

fetch() {
  curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 -o "$2" "$1"
}

# Fails unless PATTERN (extended regex) matches exactly EXPECTED lines of FILE.
expect_count() {
  local count
  count="$(grep -cE -- "$2" "$1" || true)"
  if [[ "$count" != "$3" ]]; then
    echo "error: expected $3 line(s) matching '$2', found $count; review the new release" >&2
    exit 1
  fi
}

fetch "$BASE_URL/license" "$WORK/LICENSE"
fetch "$BASE_URL/github-markdown.css" "$WORK/original.css"
sum="$(shasum -a 256 "$WORK/original.css" | cut -d' ' -f1)"

css="$WORK/github-markdown.css"
if LC_ALL=C grep -q $'\r' "$WORK/original.css"; then
  echo "error: github-markdown.css contains carriage returns" >&2
  exit 1
fi
expect_count "$WORK/original.css" '^@media \(prefers-color-scheme: dark\) \{$' 1
expect_count "$WORK/original.css" '^@media \(prefers-color-scheme: light\) \{$' 1
expect_count "$WORK/original.css" '@media' 2
expect_count "$WORK/original.css" '^ *(-webkit-)?mask-image: url\("data:image/svg\+xml,' 2
sed -E \
  -e 's/^@media \(prefers-color-scheme: dark\) \{$/@media screen and (prefers-color-scheme: dark) {/' \
  -e 's/^@media \(prefers-color-scheme: light\) \{$/@media not screen and (prefers-color-scheme: dark) {/' \
  -e '/^ *(-webkit-)?mask-image: url\("data:image\/svg\+xml,/d' \
  "$WORK/original.css" >"$css"

# Nothing may load or escape: no url(), @import, @font-face, or `</` (which would end <style>).
for forbidden in 'url\(' '@import' '@font-face' '</'; do
  expect_count "$css" "$forbidden" 0
done

# A raw-string delimiter (#…#) the CSS can't terminate or interpolate with.
hashes="#"
while grep -qF -- "\"$hashes" "$css" || grep -qF -- "\\$hashes" "$css"; do
  hashes="$hashes#"
done

swift="$WORK/source.swift"
{
  echo "// swift-format-ignore-file"
  echo "// Generated by scripts/vendor-github-markdown-css.sh from github-markdown-css $VERSION. Do not edit."
  echo "// github-markdown-css: Copyright (c) Sindre Sorhus. MIT; see Vendor/github-markdown-css/LICENSE."
  echo "// URL and SHA-256 of the original: Vendor/github-markdown-css/MANIFEST. Dark colors are screen"
  echo "// only and the anchor octicon's data: URL is removed (see the script)."
  echo
  echo "/// The vendored github-markdown-css stylesheet, the base of the GitHub theme (\`GitHubTheme\`)."
  echo "enum GitHubMarkdownCSS {"
  echo "    static let version = \"$VERSION\""
  echo
  echo "    static let stylesheet = $hashes\"\"\""
  cat "$css"
  [[ "$(tail -c 1 "$css")" == "" ]] || echo
  echo "\"\"\"$hashes"
  echo "}"
} >"$swift"

manifest="$WORK/MANIFEST"
{
  echo "# github-markdown-css vendored by scripts/vendor-github-markdown-css.sh. Do not edit."
  echo "version $VERSION"
  echo "license MIT ($BASE_URL/license)"
  echo "# sha256 url (before the script's edits)"
  echo "$sum $BASE_URL/github-markdown.css"
} >"$manifest"

mkdir -p "$VENDOR_DIR"
command cp -f "$WORK/LICENSE" "$VENDOR_DIR/LICENSE"
command cp -f "$manifest" "$VENDOR_DIR/MANIFEST"
command cp -f "$swift" "$OUTPUT"
echo "Vendored github-markdown-css $VERSION:"
cat "$VENDOR_DIR/MANIFEST"
